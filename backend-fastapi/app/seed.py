# Async seed function
# ---------------------------------------------------------------------------

async def seed() -> None:
    """Upsert all 30 products into Postgres. Idempotent: safe to re-run."""
    images = _load_product_images()

    engine = create_async_engine(
        settings.DATABASE_URL,
        connect_args={"statement_cache_size": 0},
    )
    session_factory = async_sessionmaker(bind=engine, expire_on_commit=False)

    async with session_factory() as db:
        inserted = updated = 0
        for item in SAMPLE_PRODUCTS:
            name: str = item["name"]
            slug: str = _slugify(name)

            # Override images from product_images.json if available
            img = images.get(name, {})
            image_url = img.get("imageUrl") or item["image_url"]
            image_urls = img.get("imageUrls") or item.get("image_urls", "")

            price_cents: int = _rupees_to_paise(item["price"])

            result = await db.execute(select(Product).where(Product.slug == slug))
            existing = result.scalar_one_or_none()

            if existing is None:
                db.add(
                    Product(
                        name=name,
                        slug=slug,
                        description=item.get("description"),
                        price_cents=price_cents,
                        currency="INR",
                        category=item.get("category"),
                        image_url=image_url,
                        image_urls=image_urls,
                        stock=100,
                        is_active=True,
                    )
                )
                inserted += 1
            else:
                # Update mutable fields — slug and id are stable identifiers.
                existing.name = name
                existing.description = item.get("description")
                existing.price_cents = price_cents
                existing.category = item.get("category")
                existing.image_url = image_url
                existing.image_urls = image_urls
                updated += 1

        await db.commit()
        print(f"Seed complete — inserted: {inserted}, updated: {updated}")

    await engine.dispose()


if __name__ == "__main__":
    asyncio.run(seed())
